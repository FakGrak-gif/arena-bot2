# Кулдаун, чтобы бот не спамил ответами (в секундах)
LAST_ROAST_TIME = {}

def check_for_roast(message):
    # Проверяем, есть ли в тексте плохие слова
    msg_lower = message.content.lower()
    
    # Если текст содержит одно из плохих слов
    if any(word in msg_lower for word in BAD_WORDS):
        # Проверяем кулдаун (например, не чаще 1 раза в 15 секунд на пользователя)
        current_time = time.time()
        last_time = LAST_ROAST_TIME.get(message.author.id, 0)
        
        if current_time - last_time > 15:
            LAST_ROAST_TIME[message.author.id] = current_time
            return random.choice(ROASTS)
            
    return None